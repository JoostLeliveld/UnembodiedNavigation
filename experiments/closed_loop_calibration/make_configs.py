#!/usr/bin/env python3
"""Emit the two closed-loop arms: v2 (uncorrected) vs v3 (2-DOF corrected).

The headline C1 claim is closed-loop and every observation-model result so far is
offline. This builds the matched-seed campaign that closes it.

Both arms are DERIVED from one base config and differ in exactly one key,
``manager_projection_calibration``. Generating them (rather than hand-copying two
150-line YAMLs) is what makes "matched conditions" a checked property instead of a
claim: :func:`assert_single_key_difference` fails the build if anything else moved.

v2 is an ARM, not a baseline that gets reopened -- so no v2-locked comparison is
invalidated by running this.

Usage:
    python3 experiments/closed_loop_calibration/make_configs.py
    python3 experiments/closed_loop_calibration/make_configs.py --seeds 0 1 2 3 4
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

_HERE = Path(__file__).resolve()
sys.path.insert(0, str(_HERE.parents[2] / "scripts" / "shared"))
from paths import repo_root  # noqa: E402

REPO = repo_root(_HERE)

BASE = REPO / "scripts/visibility_comparison/warehouse_full_4cam_missions.yaml"
OUT_DIR = REPO / "scripts/visibility_comparison"

CALIB_KEY = "manager_projection_calibration"
CALIB_V2 = (
    REPO / "logs/studies/multicamera_commissioning_bigwarehouse"
    / "projection_calibration_v2/projection_calibration.json"
)
CALIB_V3 = (
    REPO / "logs/studies/multicamera_commissioning_bigwarehouse"
    / "projection_calibration_v3/projection_calibration.json"
)

#: Only the deployed planner condition. The independent variable is the
#: calibration, so holding the planner fixed is the point; C1 stays available as a
#: robustness check but doubles the machine time for a question nobody asked.
CONDITION = "C2"

ARMS = {"clv2": CALIB_V2, "clv3": CALIB_V3}


def build(base: dict, calibration: Path, seeds: list[int]) -> dict:
    config = yaml.safe_load(yaml.safe_dump(base))  # deep copy through the same loader
    config[CALIB_KEY] = str(calibration)
    for task in config["tasks"].values():
        task["conditions"] = [CONDITION]
        task["seeds"] = list(seeds)
    return config


def assert_single_key_difference(a: dict, b: dict) -> None:
    """The arms must differ in exactly one key. Anything else is a confound."""
    keys = set(a) | set(b)
    differing = sorted(k for k in keys if a.get(k) != b.get(k))
    if differing != [CALIB_KEY]:
        raise SystemExit(
            f"arms differ in {differing}, expected only [{CALIB_KEY!r}] -- "
            "a matched-seed claim cannot survive a second changed key"
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    args = parser.parse_args()

    for path in (BASE, CALIB_V2, CALIB_V3):
        if not path.is_file():
            raise SystemExit(f"missing input: {path}")

    base = yaml.safe_load(BASE.read_text())
    configs = {name: build(base, calib, args.seeds) for name, calib in ARMS.items()}
    assert_single_key_difference(configs["clv2"], configs["clv3"])

    for name, config in configs.items():
        out = OUT_DIR / f"_{name}.yaml"
        out.write_text(
            "# GENERATED by experiments/closed_loop_calibration/make_configs.py -- do not\n"
            "# hand-edit; the two arms must differ in exactly one key. Regenerate instead.\n"
            + yaml.safe_dump(config, sort_keys=False),
            encoding="utf-8",
        )
        print(f"{out.relative_to(REPO)}  calib={Path(config[CALIB_KEY]).parent.name}")

    runs = len(configs) * len(base["tasks"]) * len(args.seeds)
    print(
        f"\ntasks={sorted(base['tasks'])} condition={CONDITION} seeds={args.seeds}"
        f"\n{runs} runs total ({runs // 2} per arm)"
    )
    print("\nrun with:")
    for name in ARMS:
        print(
            f"  python3 scripts/visibility_comparison/run_visibility_campaign.py "
            f"--config scripts/visibility_comparison/_{name}.yaml "
            f"--log-root logs/visibility_comparison/{name}"
        )


if __name__ == "__main__":
    main()
