#!/usr/bin/env python3
"""Recover the immutable U0--U4 config used by the completed route probes."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml


REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_selection_v1.yaml"
OUTPUT = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_selection_u_only_v1.yaml"
EXPECTED = "252823a86a9f315b85e0a6bf6f4336ad19f4294d9660bd1333cbf6b6f8a23d3c"
PROTOCOL_SOURCE = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_protocol_v1.json"
PROTOCOL_OUTPUT = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_protocol_u_only_v1.json"


def main() -> int:
    config = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    for arm in ("W0", "W3"):
        config["conditions"].pop(arm, None)
    for task in config["tasks"].values():
        task["conditions"] = [arm for arm in task["conditions"] if arm not in {"W0", "W3"}]
    OUTPUT.write_text(
        "# Generated by prepare_selected_correction_r_route_selection.py. Offline only.\n"
        + yaml.safe_dump(config, sort_keys=False),
        encoding="utf-8",
    )
    actual = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()
    if actual != EXPECTED:
        raise RuntimeError(f"recovered config hash differs: {actual}")
    protocol = json.loads(PROTOCOL_SOURCE.read_text(encoding="utf-8"))
    protocol["route_selection_config"] = str(OUTPUT.relative_to(REPO))
    protocol["route_selection_config_sha256"] = actual
    protocol["arm_order"] = ["U0", "U1", "U2", "U3", "U4"]
    protocol["planning_fields"] = {
        arm: value for arm, value in protocol["planning_fields"].items()
        if arm in protocol["arm_order"]
    }
    protocol["status"] = "frozen_after_current_u_route_selection"
    PROTOCOL_OUTPUT.write_text(
        json.dumps(protocol, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(OUTPUT)
    print(actual)
    print(PROTOCOL_OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
