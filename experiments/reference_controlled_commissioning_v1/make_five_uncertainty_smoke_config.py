#!/usr/bin/env python3
"""Derive the serialized 20-run five-arm smoke campaign from frozen routes."""
from __future__ import annotations
import hashlib, sys
from pathlib import Path
import yaml

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'experiments/reference_controlled_commissioning_v1/three_uncertainty_frozen_route_campaign_v2.yaml'
RUNTIME=ROOT/'logs/studies/reference_controlled_commissioning_v1/five_uncertainty_runtime_20260915_v1'
OUT=ROOT/'experiments/reference_controlled_commissioning_v1/five_uncertainty_one_seed_smoke_v1.yaml'
METHODS=(('U0','global_residual','global_full_residual_R'),('U1','per_camera_residual','per_camera_full_residual_R'),
         ('U2','spatial_residual','spatial_residual_R'),('U3','hierarchical_residual','hierarchical_predictive_residual_R'),
         ('U4','joint_rgb_gaussian','joint_RGB_Gaussian_mean_and_R'))
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    cfg=yaml.safe_load(BASE.read_text())
    cfg['study_title']='Five-arm commissioned perception smoke campaign'
    cfg['study_comparison']='Provisional serialized one-seed runtime smoke across constant, spatial, hierarchical, and joint RGB Gaussian perception uncertainty.'
    cfg['conditions']={}
    for arm,method,label in METHODS:
        package=RUNTIME/f'{method}.json'
        cfg['conditions'][arm]={'label':label,'manager_observation_model':method,
          'manager_covariance_profile':'commissioned_perception_r',
          'manager_perception_sensor_model_path':str(package.relative_to(ROOT)),
          'manager_perception_sensor_model_expected_sha256':digest(package)}
    for task in cfg['tasks'].values():
        route=next(iter(task['preselected_routes'].values()))
        task['conditions']=[x[0] for x in METHODS]; task['seeds']=[91500]
        task['preselected_routes']={x[0]:dict(route) for x in METHODS}
    cfg['ros_domain_id_base']=180
    header='# Generated by make_five_uncertainty_smoke_config.py from the frozen-route v2 protocol.\n'
    OUT.write_text(header+yaml.safe_dump(cfg,sort_keys=False),encoding='utf-8')
    print(OUT)
if __name__=='__main__': main()
