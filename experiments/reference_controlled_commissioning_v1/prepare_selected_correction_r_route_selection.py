#!/usr/bin/env python3
"""Prepare the current five-arm, four-task offline route-selection inputs."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml


REPO = Path(__file__).resolve().parents[2]
BASE_CONFIG = REPO / "experiments/reference_controlled_commissioning_v1/three_uncertainty_navigation_campaign_v1.yaml"
BASE_PROTOCOL = REPO / "experiments/reference_controlled_commissioning_v1/final_route_selection_protocol_v24.json"
FIELDS = REPO / "logs/studies/reference_controlled_commissioning_v1/selected_correction_r_planner_fields_20260915_v4"
RUNTIME = REPO / "logs/studies/reference_controlled_commissioning_v1/five_uncertainty_runtime_20260915_v1"
DRIVEABLE = REPO / "experiments/reference_controlled_commissioning_v1/maximal_driveable_geometry_20260915_v3.json"
CONFIG = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_selection_v4.yaml"
PROTOCOL = REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_protocol_v4.json"
TASKS = (
    "thesis09_west_to_east_north",
    "thesis09_east_to_west_south",
    "thesis09_aisle_to_crossaisle",
    "thesis09_south_to_north_central",
)
ARMS = (
    ("U0", "global_residual", "global residual R"),
    ("U1", "per_camera_residual", "per-camera residual R"),
    ("U2", "spatial_residual", "spatial residual R"),
    ("U3", "hierarchical_residual", "hierarchical predictive R"),
    ("U4", "joint_rgb_gaussian", "joint RGB Gaussian mean-and-R ablation"),
)
Q_CONTRAST_ARMS = (
    ("W0", "global_residual", "q=1 + global constant residual R"),
    ("W3", "hierarchical_residual", "q=1 + hierarchical predictive R"),
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def relative(path: Path) -> str:
    return str(path.resolve().relative_to(REPO))


def main() -> int:
    config = yaml.safe_load(BASE_CONFIG.read_text(encoding="utf-8"))
    config["study_title"] = "Selected correction matched-R offline route selection"
    config["study_comparison"] = (
        "Offline CasADi route selection on the four current thesis tasks. U0-U3 "
        "hold the selected visibility-residual correction and commissioned q fixed "
        "while changing R; U4 is a separately labelled joint RGB mean-and-R ablation."
    )
    driveable = json.loads(DRIVEABLE.read_text(encoding="utf-8"))
    config["driveable_geometry_json"] = json.dumps(
        driveable, sort_keys=True, separators=(",", ":")
    )
    config["conditions"] = {}
    for arm, runtime_method, label in ARMS:
        package = RUNTIME / f"{runtime_method}.json"
        config["conditions"][arm] = {
            "label": label,
            "manager_observation_model": runtime_method,
            "manager_covariance_profile": "commissioned_perception_r",
            "manager_perception_sensor_model_path": relative(package),
            "manager_perception_sensor_model_expected_sha256": sha256(package),
            "camera_network_artifact_path": relative(FIELDS / f"{arm.lower()}_planner_field.npz"),
        }
    for arm, runtime_method, label in Q_CONTRAST_ARMS:
        package = RUNTIME / f"{runtime_method}.json"
        config["conditions"][arm] = {
            "label": label,
            "manager_observation_model": runtime_method,
            "manager_covariance_profile": "commissioned_perception_r",
            "manager_perception_sensor_model_path": relative(package),
            "manager_perception_sensor_model_expected_sha256": sha256(package),
            "camera_network_artifact_path": relative(FIELDS / f"{arm.lower()}_planner_field.npz"),
        }
    for task in TASKS:
        config["tasks"][task] = {
            "conditions": [arm for arm, _method, _label in (*ARMS, *Q_CONTRAST_ARMS)],
            "seeds": [91500],
        }
    config["ros_domain_id_base"] = 190
    config["debug_runtime"] = True
    CONFIG.write_text(
        "# Generated by prepare_selected_correction_r_route_selection.py. Offline only.\n"
        + yaml.safe_dump(config, sort_keys=False),
        encoding="utf-8",
    )

    base = json.loads(BASE_PROTOCOL.read_text(encoding="utf-8"))
    protocol = {
        "schema_version": 4,
        "status": "frozen_before_current_route_selection",
        "supersedes": {
            "path": "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_protocol_v3.json",
            "sha256": sha256(REPO / "experiments/reference_controlled_commissioning_v1/selected_correction_r_route_protocol_v3.json"),
        },
        "amendment_reason": (
            "Replace the rounded lane-union keep-in support with the maximal registered "
            "obstacle-free floor. The legacy lane map already removed a 0.32 m semantic "
            "keep-out from each storage edge; applying the full rectangular-body gate to "
            "that support counted clearance twice. V2 reconstructs the actual registered "
            "storage/structure footprints, subtracts every robot-height physical collision "
            "AABB, and applies the locked 0.80 x 0.55 m body collision test. V3 removes "
            "the unnecessary 0.10 m release margin and retains only a 1 mm numerical guard, "
            "so the release gate requires no contact rather than extra clearance. The warehouse, tasks, uncertainty "
            "fields, and arm definitions are unchanged."
        ),
        "purpose": (
            "Select one route per current thesis task and uncertainty arm with CasADi "
            "before any Gazebo execution."
        ),
        "scientific_design": {
            "R_only_arms": ["U0", "U1", "U2", "U3"],
            "fixed_mean": "box_mlp_visibility_residual",
            "fixed_availability_q": "commissioned position GP",
            "separate_ablation": "U4 joint RGB Gaussian changes both mean and R",
        },
        "route_selection_config": relative(CONFIG),
        "route_selection_config_sha256": sha256(CONFIG),
        "driveable_geometry": {
            "path": relative(DRIVEABLE),
            "sha256": sha256(DRIVEABLE),
            "schema": driveable["schema"],
            "construction": driveable["construction"],
            "free_area_m2": driveable["free_area_m2"],
            "old_driveable_area_m2": driveable["old_driveable_area_m2"],
            "net_area_gain_m2": driveable["net_area_gain_m2"],
            "numerical_guard_m": driveable["numerical_guard_m"],
            "removed_legacy_semantic_keep_out_m": driveable[
                "removed_legacy_semantic_keep_out_m"
            ],
            "physical_release_clearance_m": driveable[
                "physical_release_clearance_m"
            ],
            "cell_count": len(driveable["prisms"]),
            "validation": driveable["validation"],
            "route_horizontal_centres": driveable["route_horizontal_centres"],
            "route_vertical_centres": driveable["route_vertical_centres"],
        },
        "tasks_yaml": base["tasks_yaml"],
        "tasks_yaml_sha256": base["tasks_yaml_sha256"],
        "selector_path": "experiments/icra_commissioning/network_route_probe.py",
        "selector_sha256": sha256(REPO / "experiments/icra_commissioning/network_route_probe.py"),
        "task_order": list(TASKS),
        "arm_order": [arm for arm, _method, _label in (*ARMS, *Q_CONTRAST_ARMS)],
        "selection_seed": 91500,
        "candidate_generation": base["candidate_generation"],
        "common_feasibility": {
            **base["common_feasibility"],
            # The release criterion is collision-free execution, not an
            # additional 0.10 m buffer.  The geometry generator already
            # applies a 1 mm numerical guard around registered obstacles.
            "minimum_static_body_clearance_m": 0.0,
            "minimum_driveable_body_clearance_m": 0.0,
        },
        "selection_rule": (
            "Use the same deterministic geometry-derived candidate seed set for every arm; "
            "run the full CasADi planner separately per task and arm; freeze each accepted result."
        ),
        "planning_fields": {
            arm: {
                "meaning": label,
                "path": relative(FIELDS / f"{arm.lower()}_planner_field.npz"),
                "sha256": sha256(FIELDS / f"{arm.lower()}_planner_field.npz"),
            }
            for arm, _method, label in (*ARMS, *Q_CONTRAST_ARMS)
        },
        "execution_gate": (
            "Do not launch Gazebo until all selected routes are frozen and the U0-U3 runtime "
            "packages bind the same selected visibility-residual correction used to fit R."
        ),
    }
    PROTOCOL.write_text(json.dumps(protocol, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(CONFIG)
    print(PROTOCOL)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
