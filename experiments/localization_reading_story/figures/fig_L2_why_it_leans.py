#!/usr/bin/env python3
"""L2 -- the mechanism slide: why the box bottom leans, and why a marked point does not.

Three panels:

  A  the north-south error of both readings, split by which way the robot faces.
     This is the table in logs/studies/keypoint_measurement/RESULTS.md as a picture.
  B  the same errors resolved along the camera's line of sight, against how the robot
     faces *relative to that line*. The box bottom is always pulled TOWARDS the camera,
     by 2 to 8 cm depending on the robot's orientation -- which is the mechanism.
  C  a diagram of why: the bottom edge of a silhouette is generated by whichever part
     of the body is nearest the camera, so it is not a fixed point on the robot.

Everything in A and B is recomputed here from the per-reading CSVs; C is a drawing.
Run: python3 experiments/localization_reading_story/figures/fig_L2_why_it_leans.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Circle, Polygon

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import reading_data as rd  # noqa: E402

BODY = 0.16          # body footprint, m (capture manifest: box_length = box_width = 0.16)
BODY_OFFSET = -0.032  # visual centre behind base_link, m (URDF, via pixel_ground_path e4)
FRONT_MARKER, REAR_MARKER = 0.040, -0.100  # capture manifest marker_geometry, m


def by_bin(values: np.ndarray, key: np.ndarray, edges: np.ndarray):
    idx = np.digitize(key, edges) - 1
    out = []
    for i in range(len(edges) - 1):
        sel = idx == i
        out.append((int(sel.sum()),
                    float(values[sel].mean()) if sel.sum() else np.nan,
                    float(values[sel].std(ddof=1) / math.sqrt(sel.sum())) if sel.sum() > 1 else 0.0))
    return out


def panel_by_heading(ax, readings) -> None:
    edges = np.linspace(0.0, 2 * math.pi, 9)
    centres = np.arange(8)
    width = 0.38
    for off, key in zip((-width / 2, +width / 2), ('box_bottom', 'keypoint_retrained')):
        r = readings[key]
        ns = r.err_cm[:, 1]
        yaw = r.col('yaw_rad') % (2 * math.pi)
        stats = by_bin(ns, yaw, edges)
        ax.bar(centres + off, [s[1] for s in stats], width=width,
               yerr=[s[2] for s in stats], color=rd.COLOUR[key], capsize=2,
               error_kw={'lw': 0.8, 'ecolor': rd.INK},
               label=('bottom of the box' if key == 'box_bottom' else 'marked point, retrained'))
    ax.axhspan(-1, 1, color=rd.KEYPOINT, alpha=0.10, zorder=0)
    ax.text(7.4, -1.6, 'within 1 cm', fontsize=7.5, color=rd.KEYPOINT, ha='right')
    ax.axhline(0, color=rd.INK, lw=0.9)
    ax.set_xticks(centres)
    ax.set_xticklabels([f'{int(math.degrees(edges[i]))}-{int(math.degrees(edges[i+1]))}'
                        for i in range(8)], fontsize=8)
    ax.set_xlabel('which way the robot faces (degrees, world frame)')
    ax.set_ylabel('north-south error (cm)\nnegative = read too far south')
    ax.set_title('A.  The box bottom\'s lean swings by three times with heading;\n'
                 'the marked point stays inside 1 cm at every heading',
                 loc='left', fontsize=10.5)
    ax.legend(loc='lower right', fontsize=8.5)


def panel_along_sightline(ax, readings) -> None:
    cam = rd.camera()
    edges = np.linspace(-math.pi, math.pi, 9)
    for key, marker in (('box_bottom', 'o'), ('keypoint_retrained', 's')):
        r = readings[key]
        e = r.err_cm
        bearing = np.arctan2(r.col('y') - cam.cam_pos[1], r.col('x') - cam.cam_pos[0])
        toward = -(e[:, 0] * np.cos(bearing) + e[:, 1] * np.sin(bearing))  # + = towards camera
        rel = (r.col('yaw_rad') - bearing + math.pi) % (2 * math.pi) - math.pi
        stats = by_bin(toward, rel, edges)
        mids = np.degrees(0.5 * (edges[:-1] + edges[1:]))
        ax.errorbar(mids, [s[1] for s in stats], yerr=[s[2] for s in stats],
                    marker=marker, color=rd.COLOUR[key], lw=2.0, capsize=2, ms=6,
                    label=('bottom of the box' if key == 'box_bottom'
                           else 'marked point, retrained'))
        for m, s in zip(mids, stats):
            if key == 'box_bottom':
                ax.annotate(f'{s[1]:.1f}', (m, s[1]), textcoords='offset points',
                            xytext=(0, 7), ha='center', fontsize=7.5, color=rd.BOX_BOTTOM)
    ax.axhline(0, color=rd.INK, lw=0.9)
    ax.set_xticks([-180, -90, 0, 90, 180])
    ax.set_xticklabels(['facing\nthe camera', 'broadside', 'driving\naway', 'broadside',
                        'facing\nthe camera'], fontsize=8)
    ax.set_xlabel('how the robot faces relative to the camera\'s line of sight')
    ax.set_ylabel('error along the line of sight (cm)\npositive = read too close to the camera')
    ax.set_title('B.  The box bottom always reads too close to the camera --\n'
                 'by 8 cm driving away, by 2 cm facing it', loc='left', fontsize=10.5)
    ax.legend(loc='upper left', fontsize=8.5)


def _footprint(ax, centre, heading_deg, colour):
    """Body footprint (a square, visual centre 3.2 cm behind base_link) plus its markers."""
    th = math.radians(heading_deg)
    c, s = math.cos(th), math.sin(th)
    def to_world(fx, fy):
        return (centre[0] + fx * c - fy * s, centre[1] + fx * s + fy * c)
    half = BODY / 2
    corners = [to_world(BODY_OFFSET + dx, dy)
               for dx, dy in ((-half, -half), (half, -half), (half, half), (-half, half))]
    ax.add_patch(Polygon(corners, closed=True, facecolor=colour, alpha=0.18,
                         edgecolor=colour, lw=1.6))
    ax.plot(*to_world(0.0, 0.0), 'o', color=rd.INK, ms=7, zorder=5)
    ax.add_patch(Circle(to_world(FRONT_MARKER, 0.0), 0.022, facecolor='#3fbfd6',
                        edgecolor='white', lw=1.0, zorder=6))
    ax.add_patch(Circle(to_world(REAR_MARKER, 0.0), 0.022, facecolor='#c2569b',
                        edgecolor='white', lw=1.0, zorder=6))
    ax.arrow(*to_world(0.0, 0.0), 0.16 * c, 0.16 * s, head_width=0.035,
             color=colour, lw=1.2, length_includes_head=True, zorder=4)
    return corners, to_world


def panel_diagram(ax) -> None:
    ax.set_aspect('equal')
    ax.set_axis_off()
    ax.set_title('C.  Why (diagram, seen from above): the bottom edge of the silhouette belongs to '
                 'whichever part of the body is nearest the camera',
                 loc='left', fontsize=10.5)
    cases = (((0.0, 0.0), 90, 'driving away from the camera'),
             ((1.30, 0.0), -90, 'facing the camera'))
    gaps = []
    for i, (centre, heading, tag) in enumerate(cases):
        corners, to_world = _footprint(ax, centre, heading, rd.BOX_BOTTOM)
        near_y = min(c[1] for c in corners)
        gaps.append(100.0 * (centre[1] - near_y))
        ax.plot([centre[0]], [near_y], 'v', color=rd.BOX_BOTTOM, ms=11, zorder=6)
        for yy in (centre[1], near_y):
            ax.plot([centre[0] - 0.30, centre[0] + 0.16], [yy, yy],
                    color=rd.MUTED, lw=0.7, ls=':', zorder=1)
        ax.annotate('', xy=(centre[0] - 0.25, near_y), xytext=(centre[0] - 0.25, centre[1]),
                    arrowprops={'arrowstyle': '<|-|>', 'color': rd.BOX_BOTTOM, 'lw': 1.4,
                                'mutation_scale': 9, 'shrinkA': 0, 'shrinkB': 0})
        ax.text(centre[0] - 0.29, 0.5 * (near_y + centre[1]),
                f'{100 * (centre[1] - near_y):.0f} cm\ntoo close', fontsize=9,
                color=rd.BOX_BOTTOM, ha='right', va='center', fontweight='bold',
                linespacing=1.25)
        ax.text(centre[0], 0.245, tag, fontsize=9.5, ha='center', va='bottom', color=rd.INK)
        ax.arrow(centre[0], -0.46, 0.0, 0.19, head_width=0.030, color=rd.MUTED, lw=1.1,
                 length_includes_head=True)
        if i == 0:      # label the parts once, on the left-hand case
            ax.annotate('where the box bottom\nprojects to', xy=(centre[0], near_y - 0.015),
                        xytext=(centre[0] + 0.30, near_y - 0.15), fontsize=8.5,
                        color=rd.BOX_BOTTOM, ha='left', va='top', linespacing=1.3,
                        arrowprops={'arrowstyle': '-', 'color': rd.BOX_BOTTOM, 'lw': 0.9})
            ax.annotate('where the robot\nactually is', xy=(centre[0] + 0.014, centre[1]),
                        xytext=(centre[0] + 0.32, centre[1] + 0.02), fontsize=8.5,
                        color=rd.INK, ha='left', va='center', linespacing=1.3,
                        arrowprops={'arrowstyle': '-', 'color': rd.INK, 'lw': 0.9})
            fx, fy = to_world(FRONT_MARKER, 0.0)
            ax.annotate('the two marker disks\n(fixed to the robot)', xy=(fx + 0.02, fy),
                        xytext=(centre[0], 0.50), fontsize=8.5, color='#8a3d78',
                        ha='center', va='bottom', linespacing=1.3,
                        arrowprops={'arrowstyle': '-', 'color': '#8a3d78', 'lw': 0.9})
    ax.text(0.65, -0.60, 'the camera is 5.5 m south of here, 4.8 m up', fontsize=8.5,
            ha='center', color=rd.MUTED)
    ax.text(1.98, 0.30,
            f'The body\'s visual centre sits 3.2 cm behind base_link and turns with the robot, so\n'
            f'the diagram predicts the gap to swing by {gaps[0] - gaps[1]:.0f} cm between these two headings.\n'
            f'Panel B measures a 5.7 cm swing, which is the mechanism confirmed on the data.\n\n'
            'The marker disks are fixed to the robot. Reading them gives the same answer at\n'
            'either heading, which is why rows 6-7 of the ladder need no heading correction\n'
            'and rows 2-5 all did.',
            fontsize=9.2, ha='left', va='top', color=rd.INK, linespacing=1.5)
    ax.set_xlim(-0.55, 3.95)
    ax.set_ylim(-0.72, 0.72)


def main() -> None:
    rd.style()
    readings = {k: rd.load_reading(k) for k in ('box_bottom', 'keypoint_retrained')}
    fig = plt.figure(figsize=(13.6, 9.3))
    grid = fig.add_gridspec(2, 2, height_ratios=[1.0, 0.72], hspace=0.42, wspace=0.28)
    panel_by_heading(fig.add_subplot(grid[0, 0]), readings)
    panel_along_sightline(fig.add_subplot(grid[0, 1]), readings)
    panel_diagram(fig.add_subplot(grid[1, :]))
    fig.suptitle('The box bottom is not a fixed point on the robot: it slides towards the '
                 'camera by 2-8 cm depending on which way the robot faces',
                 fontsize=13.5, fontweight='bold', y=0.985)
    rd.note(fig, rd.SOURCE + '  |  panels A and B recomputed from bbox_baseline/per_sample.csv '
                             'and v4_retrained/per_sample.csv; error bars are the standard error '
                             'of each bin mean. Panel C is a diagram, not a measurement '
                             '(body geometry from the capture manifest and the URDF).')
    fig.subplots_adjust(top=0.90, bottom=0.055, left=0.075, right=0.98)
    rd.save(fig, 'L2_why_the_box_bottom_leans')


if __name__ == '__main__':
    main()
