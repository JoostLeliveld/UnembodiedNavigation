"""Hit/miss expected-belief mixture in the CasADi EFE planner.

Two jobs here.

1. **Non-regression anchor.** ``R_plan`` precision-blending is FROZEN method for
   the published single-camera paper: ``honest_campaign_v1`` must stay
   reproducible bit-for-bit. ``test_flag_off_is_bit_identical_to_golden`` replays
   a fixed set of ``(u, m0, S0, goal, progress)`` points through the real
   ``make_efe_valgrad_fn`` with ``use_hit_miss_mixture=False`` and asserts exact
   float equality (``==``, not ``approx``) against values captured from the
   pre-change code. The golden literals below were generated by running this
   file's own harness against the unmodified ``casadi_efe.py``, so any drift in
   the frozen path fails here.

2. **Mixture semantics.** The mixture replaces "launder availability into R" with
   an honest two-branch expectation over a Bernoulli availability variable:
   with probability ``p_use`` a measurement arrives and the belief takes a full
   Kalman update with the *conditional* covariance ``R_cond``; with probability
   ``1 - p_use`` nothing arrives and the belief is unchanged. Tests pin the two
   endpoints, monotonicity in ``p_use``, and PSD-ness throughout.

All beliefs/fields here are synthetic test fixtures, not measurements.
"""

