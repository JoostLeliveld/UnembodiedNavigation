def _camera_H() -> np.ndarray:
    """A concrete oblique-camera homography, so the golden numbers are realistic."""
    from unav_common.camera_model import ObliqueCameraModel

    cam = ObliqueCameraModel(
        cam_pos=(-5.0, -5.5, 4.8),
        look_at=(1.5, 1.5, 0.0),
        img_width=1280,
        img_height=720,
        fov_h_rad=1.2,
    )
    return np.asarray(cam.H, dtype=float)


def _p_vis_fixture():
    """Synthetic smooth availability field (a test fixture, not a fitted GP)."""
    s = ca.MX.sym("s", 3)
    val = 1.0 / (1.0 + ca.exp(-(1.2 * s[0] - 0.8 * s[1] + 0.5)))
    return ca.Function("p_vis_fixture", [s], [val], ["state"], ["p"])


def _nogo_belief_fixture():
    """Synthetic belief-aware no-go penalty (exercises the S_drive path)."""
    m = ca.MX.sym("m", 3)
    S = ca.MX.sym("S", 3, 3)
    val = ca.exp(-(m[0] ** 2 + m[1] ** 2)) * (1.0 + ca.trace(S))
    return ca.Function("nogo_belief_fixture", [m, S], [val], ["m", "S"], ["c"])


