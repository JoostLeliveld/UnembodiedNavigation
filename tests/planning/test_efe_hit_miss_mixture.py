def test_flag_off_is_bit_identical_to_golden():
    """The frozen precision-blend path must be untouched, to the last bit."""
    for name, params, kwargs in _golden_cases():
        assert not params.use_hit_miss_mixture, f"{name} must exercise the frozen path"
        expected = GOLDEN[name]
        actual = _evaluate_case(params, kwargs)
        assert len(actual) == len(expected)
        for idx, ((val, grad), (exp_val, exp_grad)) in enumerate(zip(actual, expected)):
            assert val == float.fromhex(exp_val), f"{name}[{idx}] objective drifted"
            assert len(grad) == len(exp_grad)
            for j, (g, exp_g) in enumerate(zip(grad, exp_grad)):
                assert g == float.fromhex(exp_g), f"{name}[{idx}] grad[{j}] drifted"


def test_mixture_flag_defaults_off():
    assert cefe.CasadiEfeParams.__dataclass_fields__["use_hit_miss_mixture"].default is False
    assert _params().use_hit_miss_mixture is False


def test_flag_on_changes_the_objective():
    """Sanity: the flag actually routes somewhere else (guards a dead flag)."""
    kwargs = dict(approx="ET1", p_vis_state=_p_vis_fixture())
    off = _evaluate_case(_params(), kwargs)
    on = _evaluate_case(_params(use_hit_miss_mixture=True), kwargs)
    assert any(a[0] != b[0] for a, b in zip(off, on))


def test_flag_on_never_reads_R_miss():
    """The mixture path must not depend on the unreconciled miss endpoint.

    ``MissEndpointPolicy`` blocks quoting 40 px vs 120 px; under the mixture the
    miss branch takes no update at all, so the constant must be irrelevant.
    """
    kwargs = dict(approx="ET1", p_vis_state=_p_vis_fixture())
    a = _evaluate_case(_params(use_hit_miss_mixture=True), kwargs)
    b = _evaluate_case(
        _params(use_hit_miss_mixture=True, R_miss=np.diag([40.0 ** 2, 40.0 ** 2])),
        kwargs,
    )
    for (va, ga), (vb, gb) in zip(a, b):
        assert va == vb
        assert ga == gb


# --------------------------------------------------------------------------
# Mixture semantics, exercised on the numeric helper directly
# --------------------------------------------------------------------------

_S_PRIOR = np.array(
    [
        [0.090, 0.020, 0.003],
        [0.020, 0.140, -0.006],
        [0.003, -0.006, 0.030],
    ]
)
_JAC = np.array([[420.0, -60.0, 0.0], [35.0, 380.0, 0.0]])
_R_COND = np.diag([2.5 ** 2, 2.5 ** 2])


def _mix_cov(p_use, S=_S_PRIOR, J=_JAC, R_cond=_R_COND):
    """Numeric evaluation of the symbolic mixture, via CasADi DM."""
    out = cefe.expected_posterior_cov_ca(
        ca.DM(np.asarray(S, dtype=float)),
        ca.DM(np.asarray(J, dtype=float)),
        ca.DM(np.asarray(R_cond, dtype=float)),
        ca.DM(float(p_use)),
    )
    return np.asarray(ca.DM(out))


def _hit_cov_numpy(S=_S_PRIOR, J=_JAC, R_cond=_R_COND):
    """Independent numpy reference for the hit branch (plain Schur form)."""
    S = np.asarray(S, dtype=float)
    J = np.asarray(J, dtype=float)
    Sigma = J @ S @ J.T + np.asarray(R_cond, dtype=float)
    K = S @ J.T @ np.linalg.inv(Sigma)
    return S - K @ (J @ S)


def test_mixture_at_p0_is_the_no_update_case():
    """p_use = 0: no measurement ever arrives, so the posterior IS the prior.

    Exactly the prior, not "the prior plus a regularisation floor": the Joseph
    construction needs no state-space floor, so the no-update branch is clean.
    """
    got = _mix_cov(0.0)
    assert np.allclose(got, _S_PRIOR, atol=1e-15, rtol=0.0)


def test_mixture_at_p1_is_the_full_update_case():
    """p_use = 1: the full Kalman update with R_cond, and nothing else."""
    got = _mix_cov(1.0)
    assert np.allclose(got, _hit_cov_numpy(), atol=1e-12, rtol=0.0)


def test_mixture_is_convex_combination_of_the_two_branches():
    hit = _mix_cov(1.0)
    for p in (0.0, 0.15, 0.37, 0.5, 0.82, 1.0):
        expected = p * hit + (1.0 - p) * _S_PRIOR
        assert np.allclose(_mix_cov(p), expected, atol=1e-14, rtol=0.0)


def test_mixture_trace_is_monotone_decreasing_in_p_use():
    ps = np.linspace(0.0, 1.0, 41)
    traces = [float(np.trace(_mix_cov(p))) for p in ps]
    diffs = np.diff(traces)
    assert np.all(diffs <= 1e-12), "more availability must never increase uncertainty"
    assert traces[0] > traces[-1]


def test_mixture_is_psd_throughout():
    for p in np.linspace(0.0, 1.0, 51):
        P = _mix_cov(p)
        assert np.allclose(P, P.T, atol=1e-12)
        eig = np.linalg.eigvalsh(0.5 * (P + P.T))
        assert eig.min() > 0.0, f"non-PD posterior at p_use={p}: min eig {eig.min():.3e}"


def test_mixture_psd_for_hard_priors():
    """Near-singular and strongly correlated priors must still yield a PD mixture."""
    hard = [
        np.diag([1e-6, 1e-6, 1e-6]),
        np.array([[0.5, 0.4999, 0.0], [0.4999, 0.5, 0.0], [0.0, 0.0, 1e-5]]),
        np.array([[2.0, 0.0, 1.4], [0.0, 2.0, 0.0], [1.4, 0.0, 1.0]]),
    ]
    for S in hard:
        for p in (0.0, 0.25, 0.5, 0.75, 1.0):
            P = _mix_cov(p, S=S)
            eig = np.linalg.eigvalsh(0.5 * (P + P.T))
            assert eig.min() > 0.0


def test_mixture_never_exceeds_the_prior_in_loewner_order():
    for p in np.linspace(0.0, 1.0, 21):
        delta = _S_PRIOR - _mix_cov(p)
        eig = np.linalg.eigvalsh(0.5 * (delta + delta.T))
        assert eig.min() >= -1e-9, "a measurement must never inflate the belief"


def test_expected_uncertainty_matches_branch_weighted_entropy():
    """The epistemic scalar is E[H], i.e. H(prior) - p_use * mutual information."""

    def ent(P):
        n = P.shape[0]
        return 0.5 * (n * math.log(2.0 * math.pi * math.e) + math.log(np.linalg.det(P)))

    h_prior = ent(_S_PRIOR)
    h_hit = ent(_hit_cov_numpy())
    for p in (0.0, 0.3, 0.61, 1.0):
        got = float(
            ca.DM(
                cefe.expected_posterior_uncertainty_ca(
                    ca.DM(_S_PRIOR), ca.DM(_JAC), ca.DM(_R_COND), ca.DM(float(p))
                )
            )
        )
        assert got == pytest.approx(p * h_hit + (1.0 - p) * h_prior, rel=1e-9, abs=1e-9)

    # information gain is non-negative, so the scalar is monotone decreasing
    assert h_hit <= h_prior


def test_expected_uncertainty_is_monotone_decreasing_in_p_use():
    vals = [
        float(
            ca.DM(
                cefe.expected_posterior_uncertainty_ca(
                    ca.DM(_S_PRIOR), ca.DM(_JAC), ca.DM(_R_COND), ca.DM(float(p))
                )
            )
        )
        for p in np.linspace(0.0, 1.0, 41)
    ]
    assert np.all(np.diff(vals) <= 1e-12)
    assert vals[0] > vals[-1]


